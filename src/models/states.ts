export function getStateFromZip(zip?: string | null) {
    if (!zip || zip.length < 3) return null
    if (zip === '96799') return 'AS'
    const prefix = Number(zip.slice(0, 3))
    return (
        zipPrefixStates.find(
            ([start, end]) => prefix >= start && prefix <= end
        )?.[2] ?? null
    )
}
